#!/usr/bin/env python3
"""Verify the finished release ZIP against committed HEAD blobs, not staging."""

import stat
import subprocess
import sys
import unicodedata
import zipfile
from pathlib import Path


def committed_blobs(root):
    """Return exact HEAD file object IDs using Git's NUL-delimited tree."""
    output = subprocess.check_output(["git", "-C", str(root), "ls-tree", "-r", "-z", "HEAD"])
    blobs = {}
    for entry in output.split(b"\0"):
        if not entry:
            continue
        metadata, path = entry.split(b"\t", 1)
        mode, kind, object_id = metadata.split(b" ", 2)
        if kind == b"blob" and mode in (b"100644", b"100755"):
            blobs[path.decode("utf-8", "surrogateescape")] = object_id.decode("ascii")
    return blobs


def validate_archive_member(member, seen, portable_seen):
    """Refuse ambiguous, unsafe, or non-file ZIP entries before reading bytes."""
    name = member.filename
    if name in seen:
        raise ValueError(f"Refusing duplicate ZIP member: {name}")
    seen.add(name)
    portable_name = unicodedata.normalize("NFKC", name).casefold()
    if portable_name in portable_seen and portable_seen[portable_name] != name:
        raise ValueError(f"Refusing colliding ZIP paths: {portable_seen[portable_name]} and {name}")
    portable_seen[portable_name] = name
    if not name.startswith("slateframe/"):
        raise ValueError(f"Refusing ZIP member outside theme root: {name}")
    parts = name.split("/")
    if "\\" in name or any(part in ("", ".", "..") for part in (parts[:-1] if member.is_dir() else parts)):
        raise ValueError(f"Refusing unsafe ZIP member path: {name}")
    if member.is_dir():
        if parts[-1] != "" or member.file_size:
            raise ValueError(f"Refusing invalid ZIP directory: {name}")
    elif not parts[-1]:
        raise ValueError(f"Refusing invalid ZIP member path: {name}")
    if member.flag_bits & 1 or member.comment:
        raise ValueError(f"Refusing encrypted or commented ZIP member: {name}")
    # ZIPs generated by our writer are Unix entries. Refuse symlink/device
    # metadata even if the decompressed bytes happen to match a HEAD blob.
    if member.create_system == 3:
        mode = member.external_attr >> 16
        if stat.S_IFMT(mode) not in (0, stat.S_IFDIR if member.is_dir() else stat.S_IFREG):
            raise ValueError(f"Refusing non-regular ZIP member: {name}")



def expected_distribution_paths(root, committed):
    """Derive required ZIP files from HEAD and the committed rsync exclusions.

    An archive with only style.css previously passed byte attestation even
    when the rest of the distributable theme had been silently dropped.
    """
    import fnmatch

    try:
        ignored = subprocess.check_output(
            ["git", "-C", str(root), "show", "HEAD:.distignore"],
            stderr=subprocess.DEVNULL,
        ).decode("utf-8")
    except subprocess.CalledProcessError:
        # Tiny independent Git fixtures may not carry the theme's distignore.
        ignored = "docs/\ntests/\nbin/\n.github/\n.distignore\n"

    patterns = []
    for raw in ignored.splitlines():
        pattern = raw.strip()
        if not pattern or pattern.startswith("#"):
            continue
        if pattern.startswith(("!", "/")) or "\\" in pattern:
            raise ValueError(f"Unsupported distribution exclusion: {pattern}")
        patterns.append(pattern)

    def excluded(path):
        parts = path.split("/")
        for pattern in patterns:
            directory = pattern.endswith("/")
            name = pattern.rstrip("/")
            if directory:
                candidates = parts[:-1]
            else:
                candidates = parts
            if "/" in name:
                # Slash-containing rules are relative to the theme root.
                if path == name or path.startswith(name + "/") and directory:
                    return True
            elif any(fnmatch.fnmatchcase(part, name) for part in candidates):
                return True
        return False

    return {path for path in committed if not excluded(path)}


def verify(root, archive_path):
    """Fail closed if any final ZIP file differs from the source revision."""
    committed = committed_blobs(root)
    expected = expected_distribution_paths(root, committed)
    with zipfile.ZipFile(archive_path, "r") as archive:
        if archive.comment:
            raise ValueError("Refusing commented ZIP archive")
        seen = set()
        portable_seen = {}
        files = 0
        present = set()
        for member in archive.infolist():
            validate_archive_member(member, seen, portable_seen)
            if member.is_dir():
                continue
            files += 1
            name = member.filename
            relative = name[len("slateframe/"):]
            present.add(relative)
            if relative not in committed:
                raise ValueError(f"Refusing ZIP member absent from HEAD: {name}")
            # Git hash-object computes the repository's object format (SHA-1
            # or SHA-256). Compare actual uncompressed archive bytes, not a
            # mutable staging file or CRC that an archive writer can replace.
            content = archive.read(member)
            actual = subprocess.check_output(
                ["git", "-C", str(root), "hash-object", "--stdin"],
                input=content,
            ).decode("ascii").strip()
            if actual != committed[relative]:
                raise ValueError(f"Refusing ZIP bytes differing from HEAD: {name}")
        if not files:
            raise ValueError("Refusing ZIP archive without theme files")
        missing = expected - present
        unexpected = present - expected
        if missing or unexpected:
            raise ValueError(
                f"ZIP distribution differs from committed HEAD: missing={sorted(missing)!r}, "
                f"excluded={sorted(unexpected)!r}"
            )


if __name__ == "__main__":
    try:
        verify(Path(sys.argv[1]), Path(sys.argv[2]))
    except (ValueError, OSError, subprocess.CalledProcessError, zipfile.BadZipFile) as error:
        raise SystemExit(str(error)) from error
